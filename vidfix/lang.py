_current = {"en"}


def set_lang(lang: str):
    if lang in _STRINGS:
        _current.clear()
        _current.add(lang)


def t(key: str, **kwargs) -> str:
    """Translate a key in the current language, with .format() support."""
    lang = next(iter(_current))
    template = _STRINGS[lang].get(key) or _STRINGS["en"].get(key, key)
    return template.format(**kwargs) if kwargs else template


def available_langs():
    return list(_STRINGS.keys())
